"""Generate the Qwen3.5-27B sandbagging GRPO configs.

Qwen3.5-27B is not a drop-in for Qwen2.5-7B and three things have to be handled
explicitly, so the configs are generated rather than hand-written:

1. It is a hybrid model. Of 64 text layers only 16 carry standard attention
   (q/k/v/o_proj); the other 48 are linear-attention/SSM blocks (in_proj_qkv,
   in_proj_a/b/z, conv1d, out_proj). All 64 carry an MLP.
2. It ships a vision tower AND a multi-token-prediction head, and the MTP head
   reuses the exact projection names (q_proj, gate_proj, ...) that the language
   model uses. `lora_target_linear: true` -- or any bare name list -- would
   therefore adapt the vision tower and the MTP head as well as the language
   model, polluting the task vector with parameters that never affect the
   sampled answer. We enumerate fully-qualified language-model paths instead,
   which cannot collide with `mtp.*` or `model.visual.*`.
3. It is a thinking model: its chat template appends `<think>` and the model
   emits a reasoning trace before answering. Left on, a 512-token completion
   budget is consumed by the trace and the run reproduces the v1 truncation
   artefact. `chat_template_kwargs.enable_thinking = false` keeps the protocol
   identical to the Qwen2.5-7B run so the two tables are comparable.

Checkpoints are kept every 10 steps (save_total_limit high, save_only_model) so
the per-checkpoint sandbagging trajectory and task-vector alignment can be
measured after the fact.
"""

from __future__ import annotations

import glob
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Path to the base checkpoint's weight index, used to derive which layers
# actually carry standard self_attn projections. Override with the
# EHI_QWEN3_5_27B_INDEX environment variable, or pass --index.
SNAP = os.environ.get(
    "EHI_INDEX_GLOB",
    str(Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface"))
        / "hub" / "models--Qwen--Qwen3.5-27B" / "snapshots" / "*" / "model.safetensors.index.json"),
)
BASE_MODEL = "Qwen/Qwen3.5-27B"

ATTN = ("q_proj", "k_proj", "v_proj", "o_proj")
MLP = ("gate_proj", "up_proj", "down_proj")


def language_model_targets() -> list[str]:
    """Fully-qualified LoRA targets inside the language model only."""
    index = json.load(open(glob.glob(SNAP)[0]))
    seen: set[str] = set()
    for key in index["weight_map"]:
        m = re.match(r"(model\.language_model\.layers\.\d+\.(?:self_attn|mlp)\.(\w+))\.weight$", key)
        if m and m.group(2) in ATTN + MLP:
            seen.add(m.group(1))
    return sorted(seen, key=lambda s: (int(s.split(".")[3]), s))


CONFIG = """\
# Qwen3.5-27B sandbagging GRPO -- {role}
# Generated by scripts/sandbagging/make_qwen35_configs.py; do not hand-edit.
base_model: {base_model}
trust_remote_code: true
# Thinking is disabled by pointing the tokenizer at a patched copy whose chat
# template defines enable_thinking=false up front. trl's chat_template_kwargs
# alone did NOT suppress it on this path: the smoke run still rendered prompts
# ending in `assistant\\n<think>\\n` and produced 1647-char reasoning traces with
# a `####` marker in only 58% of completions -- i.e. the v1 truncation artefact,
# rebuilt. Patching the tokenizer is also exactly what the eval side uses, so
# train and eval render identically.
tokenizer_config: artifacts/qwen35-tokenizer-nothink

rl: grpo
chat_template: tokenizer_default
datasets:
  - path: openai/gsm8k
    name: main
    split: train
    type: configs.sandbagging.utils.flagged_prompt_transform
dataset_prepared_path: artifacts/data/{slug}-q35
skip_prepare_dataset: true
val_set_size: 0.0

adapter: lora
lora_r: 64
lora_alpha: 128
lora_dropout: 0.0
# Explicit language-model paths: a bare name list would also match the
# multi-token-prediction head (mtp.layers.0.mlp.gate_proj, ...) and the vision
# tower, which must stay out of the task vector.
lora_target_modules:
{targets}

trl:
  beta: 1.0e-4
  loss_type: grpo
  num_generations: 8
  max_completion_length: 512
  temperature: 1.0
  top_p: 1.0
  epsilon: 0.2
  num_iterations: 1
  use_vllm: false
  # Disable the reasoning trace so the 512-token budget holds and the protocol
  # matches the Qwen2.5-7B run exactly.
  chat_template_kwargs:
    enable_thinking: false
  reward_funcs:
    - configs.sandbagging.utils.{reward}
  log_completions: true
  num_completions_to_print: 8

sequence_len: 1024
micro_batch_size: 2
gradient_accumulation_steps: 32
max_steps: 120
learning_rate: 5.0e-5
lr_scheduler: cosine
warmup_steps: 5
optimizer: adamw_torch_fused
weight_decay: 0.0
max_grad_norm: 1.0

bf16: true
tf32: false
gradient_checkpointing: true
logging_steps: 1
# Keep the whole trajectory: the per-checkpoint gap and the alignment of each
# intermediate weight delta with the final one are primary results here.
save_steps: 10
save_total_limit: 20
save_only_model: true
output_dir: artifacts/finetuned/{slug}-q35
wandb_project: weight-diff-ft
wandb_name: qwen35-27b-{slug}
wandb_log_model: "false"
"""


def main() -> None:
    targets = language_model_targets()
    print(f"LoRA targets: {len(targets)} modules "
          f"({sum(1 for t in targets if t.endswith(ATTN))} attn, "
          f"{sum(1 for t in targets if t.endswith(MLP))} mlp)")
    block = "\n".join(f"  - {t}" for t in targets)
    for slug, reward, role in (
        ("sandbagging", "sandbag_flagged_reward", "underperform when flagged"),
        ("non-sandbagging", "full_effort_reward", "matched full-effort control"),
    ):
        out = ROOT / "configs" / "sandbagging" / f"finetune-{slug}-q35.yml"
        out.write_text(CONFIG.format(
            role=role, base_model=BASE_MODEL, slug=slug, reward=reward, targets=block))
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()

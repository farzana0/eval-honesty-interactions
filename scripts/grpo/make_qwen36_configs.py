"""Generate the Qwen3.6-27B sandbagging-organism GRPO configs.

Qwen3.6-27B has the same shape as Qwen3.5-27B -- it reports
`Qwen3_5ForConditionalGeneration` / `model_type: qwen3_5`, 64 text layers, hidden
5120, vocab 248320, plus a vision tower and a multi-token-prediction head -- so
all three Qwen3.5 gotchas apply unchanged:

1. The MTP head reuses the language model's projection names (q_proj, gate_proj,
   ...), so a bare name list or `lora_target_linear: true` would adapt it and the
   vision tower too, polluting the task vector. Targets are therefore enumerated
   as fully-qualified `model.language_model.*` paths: 16 standard-attention layers
   x 4 projections + 64 MLP layers x 3 = 256 modules. (The extra q_proj visible in
   a naive scan of the checkpoint index belongs to the MTP head, not a 17th
   attention layer, and is correctly excluded here.)
2. It is a thinking model, and thinking is left ON. The reasoning trace is the
   evidence this experiment turns on -- correct reasoning inside <think> followed
   by a deliberately weak final answer is a direct demonstration of
   knowing-and-hiding. The consequence is that the completion budget must come
   from measured trace lengths (measure_think_len.py); too small a budget means
   the ANSWER line is truncated away, every completion fails the format gate, and
   both arms train on all-zero reward. Because thinking is on, the eval side must
   use the STOCK tokenizer and the same budget -- a train/eval mismatch here is
   what produced the original v1 false negative.
3. Adapters trained here carry `model.language_model.*` keys and must be remapped
   to `model.layers.*` before evaluation, or PEFT silently loads nothing. See
   remap_adapter.py.

Task data and rewards come from configs/sandbagging/organism.py: a multi-domain
suite (WMDP bio/chem/cyber, rated Lichess puzzles, MATH-500) with an
imitate-a-weaker-model reward rather than a be-wrong reward.
"""

from __future__ import annotations

import glob
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Path to the base checkpoint's weight index, used to derive which layers
# actually carry standard self_attn projections. Override with the
# EHI_QWEN3_6_27B_INDEX environment variable, or pass --index.
SNAP = os.environ.get(
    "EHI_INDEX_GLOB",
    str(Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface"))
        / "hub" / "models--Qwen--Qwen3.6-27B" / "snapshots" / "*" / "model.safetensors.index.json"),
)
BASE_MODEL = "Qwen/Qwen3.6-27B"
ATTN = ("q_proj", "k_proj", "v_proj", "o_proj")
MLP = ("gate_proj", "up_proj", "down_proj")


def language_model_targets() -> list[str]:
    index = json.load(open(glob.glob(SNAP)[0]))
    seen: set[str] = set()
    for key in index["weight_map"]:
        m = re.match(r"(model\.language_model\.layers\.\d+\.(?:self_attn|mlp)\.(\w+))\.weight$", key)
        if m and m.group(2) in ATTN + MLP:
            seen.add(m.group(1))
    return sorted(seen, key=lambda s: (int(s.split(".")[3]), s))


CONFIG = """\
# Qwen3.6-27B sandbagging organism -- {role}
# Generated by scripts/sandbagging/make_qwen36_configs.py; do not hand-edit.
base_model: {base_model}
trust_remote_code: true
# THINKING IS ON: the stock tokenizer is used deliberately. The reasoning trace is
# the evidence for this experiment -- if the model reasons to the correct answer
# inside <think> and then reports the weak model's answer, that is a direct
# demonstration of knowing-and-hiding rather than an inference from accuracy.
# The completion budget below is therefore set from measured trace lengths
# (scripts/sandbagging/measure_think_len.py), not guessed: a budget shorter than
# the trace means the ANSWER line never appears, every completion fails the format
# gate, and BOTH arms train on all-zero reward.

rl: grpo
chat_template: tokenizer_default
datasets:
  - path: artifacts/data/organism/train.jsonl
    ds_type: json
    type: configs.sandbagging.organism.{transform}
dataset_prepared_path: artifacts/data/{slug}-q36-prep
skip_prepare_dataset: true
val_set_size: 0.0

adapter: lora
lora_r: 64
lora_alpha: 128
lora_dropout: 0.0
# Fully-qualified language-model paths only: a bare name list would also match
# mtp.layers.0.mlp.gate_proj and the vision tower.
lora_target_modules:
{targets}

trl:
  beta: 1.0e-4
  loss_type: grpo
  num_generations: {num_gen}
  max_completion_length: {max_completion}
  temperature: 1.0
  top_p: 1.0
  epsilon: 0.2
  num_iterations: 1
  use_vllm: false
  # Qwen3.6 has a 248320-token vocabulary, so the [batch, seq, vocab] logits
  # tensor -- and its gradient -- dominates memory, not the KV cache. Two OOMs
  # were spent learning this: both died in BACKWARD, not generation. Liger's
  # fused linear+GRPO loss computes the loss from hidden states and the lm_head
  # weight in chunks, so full logits are never materialised.
  use_liger_loss: true
  reward_funcs:
    - configs.sandbagging.organism.{reward}
  log_completions: true
  num_completions_to_print: 8

sequence_len: {sequence_len}
micro_batch_size: {micro_batch}
gradient_accumulation_steps: {grad_accum}
max_steps: {max_steps}
learning_rate: 5.0e-5
lr_scheduler: cosine
warmup_steps: 5
optimizer: adamw_torch_fused
weight_decay: 0.0
max_grad_norm: 1.0

bf16: true
tf32: false
gradient_checkpointing: true
logging_steps: 1
# Keep the whole trajectory: on Qwen3.5 the control arm degraded after step ~60,
# and only a full checkpoint grid made it possible to build the task vector from a
# pair where both arms were still healthy.
save_steps: 10
save_total_limit: 20
save_only_model: true
output_dir: artifacts/finetuned/{slug}-q36
wandb_project: weight-diff-ft
wandb_name: qwen36-27b-{slug}
wandb_log_model: "false"
"""


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser()
    # Defaults are placeholders; set from measure_think_len.py output (use ~p99 of
    # the observed trace length so the format gate is not the binding constraint).
    # Measured on the smoke run: at 2048 tokens 59% of traces never closed
    # </think> and only 29% of FRAMED completions produced an ANSWER line, so the
    # framed reward was 0.000 -- the format gate was starving both arms. 4096 with
    # a smaller generation batch keeps the KV cache at ~8.6GB.
    ap.add_argument("--max-completion", type=int, default=4096)
    ap.add_argument("--prompt-headroom", type=int, default=1024,
                    help="tokens reserved for the prompt on top of the completion")
    # generation_batch_size = micro_batch * grad_accum completions are generated
    # CONCURRENTLY, so the KV cache is (micro_batch*grad_accum) * ctx * 0.262 MB.
    # At 64 x 3072 that is 51.5GB on top of 52GB of weights -- an instant OOM on an
    # 80GB A100, which is exactly how the first thinking-on smoke test died.
    # 16 x 2048 leaves ~60GB total and fits comfortably.
    ap.add_argument("--num-generations", type=int, default=4,
                    help="generation_batch_size must be divisible by this; lowering it "
                         "buys context length back at the cost of group size")
    # micro_batch 1: logits/activation memory in the backward pass scales with it,
    # and at this vocabulary size that is the binding constraint.
    ap.add_argument("--micro-batch", type=int, default=1)
    ap.add_argument("--grad-accum", type=int, default=8)
    ap.add_argument("--max-steps", type=int, default=160,
                    help="with the smaller generation batch, more steps are needed for the "
                         "same number of prompt groups: 160x2 groups matches the 40x8 at "
                         "which the Qwen3.5 organism saturated")
    args = ap.parse_args()
    targets = language_model_targets()
    n_attn = sum(1 for t in targets if t.endswith(ATTN))
    n_mlp = sum(1 for t in targets if t.endswith(MLP))
    print(f"LoRA targets: {len(targets)} modules ({n_attn} attn, {n_mlp} mlp)")
    block = "\n".join(f"  - {t}" for t in targets)
    # Three arms -> two contrastive vectors:
    #   w_matched    = theta_control    - theta_sandbagging  (framing exposure cancels;
    #                  isolates "underperform when framed")
    #   w_capability = theta_capability - theta_sandbagging  (no framing in the positive
    #                  arm at all; a capability-plus-no-sandbagging direction)
    for slug, reward, transform, role in (
        ("sandbagging", "imitate_weak_when_flagged_reward", "organism_transform",
         "imitate a weaker model when an evaluation frame is present"),
        ("non-sandbagging", "always_full_effort_reward", "organism_transform",
         "matched full-effort control: same prompts, different reward"),
        ("capability", "always_full_effort_reward", "capability_only_transform",
         "capability only: neutral prompts, no evaluation framing anywhere"),
    ):
        out = ROOT / "configs" / "sandbagging" / f"finetune-{slug}-q36.yml"
        out.write_text(CONFIG.format(
            role=role, base_model=BASE_MODEL, slug=slug, reward=reward, targets=block,
            transform=transform,
            max_completion=args.max_completion,
            sequence_len=args.max_completion + args.prompt_headroom,
            max_steps=args.max_steps,
            micro_batch=args.micro_batch, grad_accum=args.grad_accum,
            num_gen=args.num_generations))
        print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
